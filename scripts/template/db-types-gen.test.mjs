// DB 타입 생성기(scripts/db-types-gen.mjs) 테스트. 실행: 루트에서 `pnpm test`
//
// 임시 폴더에 작은 마이그레이션을 두고 생성기를 돌려, 나온 database.types.ts 의 글자를 본다.
// 생성물이 supabase-js 에 실제로 먹는지는 web·mobile 의 타입 시험(supabase-browser.test.ts 등)이 본다.
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { before, describe, it } from "node:test";
import { fileURLToPath } from "node:url";
import { generateTypes } from "../db-types-gen.mjs";

const generator = join(dirname(fileURLToPath(import.meta.url)), "..", "db-types-gen.mjs");

const tempDir = (t) => {
  const dir = mkdtempSync(join(tmpdir(), "db-types-gen-test-"));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  return dir;
};

const writeFiles = (base, files) =>
  Object.entries(files).forEach(([path, content]) => {
    mkdirSync(dirname(join(base, path)), { recursive: true });
    writeFileSync(join(base, path), content);
  });

// 출력에서 "이름: {" 로 열린 묶음의 안쪽 줄을 꺼낸다. 이름을 여러 개 주면 차례로 안쪽으로 들어간다.
const blockLines = (text, ...names) =>
  names.reduce((lines, name) => {
    const start = lines.findIndex((line) => line.trim() === `${name}: {`);
    assert.notEqual(start, -1, `${names.join(" > ")} 묶음이 출력에 없다`);
    const closing = `${lines[start].slice(0, lines[start].length - lines[start].trimStart().length)}}`;
    const end = lines.findIndex((line, i) => i > start && line === closing);
    return lines.slice(start + 1, end);
  }, text.split("\n"));
const fields = (text, ...names) => blockLines(text, ...names).map((line) => line.trim());

// 일부러 이름순이 아닌 순서로 만든다(things → parts → links). 출력은 이름순이어야 한다.
const RICH_SCHEMA = `
create type public.mood as enum ('sad', 'ok', 'happy');
create type public.pair as (a int, b text);
create domain public.short_text as varchar(10);
create table public.things (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users (id),
  label varchar(20) not null,
  note text,
  amount numeric,
  score int default 0,
  tags text[] not null default '{}',
  moods public.mood[],
  meta jsonb,
  feeling public.mood,
  doubled int generated always as (score * 2) stored,
  dur interval,
  born date,
  at timestamptz not null default now(),
  ok boolean not null default true,
  nick public.short_text,
  pt point
);
create table public.parts (
  id int generated by default as identity primary key,
  thing_id bigint unique references public.things (id),
  x int
);
create table public.links (a bigint references public.things (id), b int references public.parts (id), primary key (a, b));
create view public.thing_labels as select id, label from public.things;
create view public.thing_count as select count(*) as n from public.things;
create function public.add(a int, b int default 1) returns int language sql as 'select a + b';
create function public.list_things(min_score int) returns setof public.things language sql as 'select * from public.things where score >= min_score';
create function public.score_table(n int) returns table (x int, y text) language sql as 'select 1, ''a''';
create function public.noop() returns void language sql as '';
create function public.touch() returns trigger language plpgsql as 'begin return new; end';
`;

describe("마이그레이션 → database.types.ts", () => {
  const generated = { text: "" };
  before(async () => {
    const dir = mkdtempSync(join(tmpdir(), "db-types-gen-test-"));
    try {
      writeFiles(dir, { "20260101000001_rich.sql": RICH_SCHEMA });
      generated.text = await generateTypes(dir);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("PostgreSQL 타입을 TypeScript 타입으로 옮기고, null 이 될 수 있는 열에 | null 을 붙인다", () => {
    assert.deepEqual(fields(generated.text, "things", "Row"), [
      "amount: number | null",
      "at: string",
      "born: string | null",
      "doubled: number | null",
      "dur: string | null",
      'feeling: Database["public"]["Enums"]["mood"] | null',
      "id: number",
      "label: string",
      "meta: Json | null",
      'moods: Database["public"]["Enums"]["mood"][] | null',
      "nick: string | null",
      "note: string | null",
      "ok: boolean",
      "pt: unknown",
      "score: number | null",
      "tags: string[]",
      "user_id: string",
    ]);
  });

  it("Insert 는 기본값·null 허용·identity 열을 선택으로 두고, 항상 생성되는 열은 never 로 막는다", () => {
    assert.deepEqual(fields(generated.text, "things", "Insert"), [
      "amount?: number | null",
      "at?: string",
      "born?: string | null",
      "doubled?: never",
      "dur?: string | null",
      'feeling?: Database["public"]["Enums"]["mood"] | null',
      "id?: never",
      "label: string",
      "meta?: Json | null",
      'moods?: Database["public"]["Enums"]["mood"][] | null',
      "nick?: string | null",
      "note?: string | null",
      "ok?: boolean",
      "pt?: unknown",
      "score?: number | null",
      "tags?: string[]",
      "user_id: string",
    ]);
    // generated by default identity 는 직접 넣을 수도 있어서 never 가 아니라 선택이다.
    assert.ok(fields(generated.text, "parts", "Insert").includes("id?: number"));
  });

  it("Update 는 모든 열이 선택이고, 항상 생성되는 열은 never 로 막는다", () => {
    const update = fields(generated.text, "things", "Update");
    assert.ok(
      update.every((field) => /^[\w"]+\?: /.test(field)),
      update.join("\n"),
    );
    assert.ok(update.includes("id?: never") && update.includes("doubled?: never"));
    assert.ok(update.includes("label?: string"));
  });

  it("Relationships 에는 public 안의 외래 키만 넣는다 (auth.users 를 가리키는 키는 뺀다)", () => {
    assert.ok(
      blockLines(generated.text, "things").some((line) => line.trim() === "Relationships: []"),
    );
    assert.deepEqual(
      blockLines(generated.text, "parts")
        .map((line) => line.trim())
        .slice(-9),
      [
        "Relationships: [",
        "{",
        'foreignKeyName: "parts_thing_id_fkey"',
        'columns: ["thing_id"]',
        "isOneToOne: true",
        'referencedRelation: "things"',
        'referencedColumns: ["id"]',
        "},",
        "]",
      ],
    );
  });

  it("트리거 함수는 빼고, 인자 없는 함수는 Args: never 로 둔다", () => {
    const functions = fields(generated.text, "Functions");
    assert.ok(
      !functions.some((line) => line.startsWith("touch")),
      "returns trigger 함수는 rpc 로 못 부르니 빠져야 한다",
    );
    assert.deepEqual(fields(generated.text, "Functions", "noop"), [
      "Args: never",
      "Returns: undefined",
    ]);
    assert.deepEqual(fields(generated.text, "Functions", "add"), [
      "Args: { a: number; b?: number }",
      "Returns: number",
    ]);
    assert.deepEqual(fields(generated.text, "Functions", "list_things"), [
      "Args: { min_score: number }",
      'Returns: Database["public"]["Tables"]["things"]["Row"][]',
    ]);
    assert.deepEqual(fields(generated.text, "Functions", "score_table"), [
      "Args: { n: number }",
      "Returns: { x: number; y: string }[]",
    ]);
  });

  it("enum 은 문자열 합집합, 복합 타입은 null 허용 속성, 고칠 수 없는 뷰는 Row 만 둔다", () => {
    assert.deepEqual(fields(generated.text, "Enums"), ['mood: "sad" | "ok" | "happy"']);
    assert.deepEqual(fields(generated.text, "CompositeTypes", "pair"), [
      "a: number | null",
      "b: string | null",
    ]);
    assert.deepEqual(
      fields(generated.text, "thing_count").filter((line) => line.endsWith("{")),
      ["Row: {"],
    );
    assert.deepEqual(fields(generated.text, "thing_labels", "Insert"), [
      "id?: number | null",
      "label?: string | null",
    ]);
  });

  it("표·열을 이름순으로 내고, 같은 마이그레이션이면 출력이 글자 하나까지 같다", async (t) => {
    const tables = blockLines(generated.text, "Tables")
      .filter((line) => /^ {6}\w+: \{$/.test(line))
      .map((line) => line.trim());
    assert.deepEqual(tables, ["links: {", "parts: {", "things: {"]);

    const dir = tempDir(t);
    writeFiles(dir, { "20260101000001_rich.sql": RICH_SCHEMA });
    assert.equal(await generateTypes(dir), generated.text);
  });

  it("supabase gen types 와 같은 바깥 모양(배너·Json·도우미 타입)을 낸다", () => {
    assert.match(generated.text, /^\/\/ 생성물 — 손으로 고치지 말 것 \(pnpm db:types\)\./);
    [
      "export type Json =",
      "export type Database = {",
      "export type Tables<",
      "export type TablesInsert<",
      "export type TablesUpdate<",
      "export type Enums<",
      "export type CompositeTypes<",
    ].forEach((head) => assert.ok(generated.text.includes(head), `${head} 가 없다`));
  });
});

describe("pnpm db:types · pnpm check:db-types", () => {
  const SMALL =
    "create table public.notes (id text primary key, body text);\nalter table public.notes enable row level security;\n";

  // web 만 있는 저장소. mobile 은 package.json 이 없어 없는 폴더로 본다.
  const webOnlyRepo = (t) => {
    const root = tempDir(t);
    writeFiles(root, {
      "web/package.json": "{}\n",
      "supabase/migrations/20260101000001_init.sql": SMALL,
    });
    return root;
  };

  const runGenerator = (root, ...args) => {
    const result = spawnSync(process.execPath, [generator, "--root", root, ...args], {
      encoding: "utf8",
    });
    return { code: result.status, output: `${result.stdout}${result.stderr}` };
  };

  const WEB_TYPES = "web/lib/database.types.ts";

  it("package.json 이 있는 폴더에만 만든다", (t) => {
    const root = webOnlyRepo(t);

    const { code, output } = runGenerator(root);

    assert.equal(code, 0, output);
    assert.match(readFileSync(join(root, WEB_TYPES), "utf8"), /notes: \{/);
    assert.equal(existsSync(join(root, "mobile/lib/database.types.ts")), false);
  });

  it("--check 는 생성물이 없거나, 손으로 고쳤거나, 마이그레이션이 늘면 고치는 법과 함께 실패한다", (t) => {
    const root = webOnlyRepo(t);
    const missing = runGenerator(root, "--check");
    assert.equal(missing.code, 1);
    assert.match(missing.output, /web\/lib\/database\.types\.ts/);

    assert.equal(runGenerator(root).code, 0);
    const fresh = readFileSync(join(root, WEB_TYPES), "utf8");
    assert.equal(runGenerator(root, "--check").code, 0);

    writeFileSync(join(root, WEB_TYPES), fresh.replace("body: string | null", "body: string"));
    const edited = runGenerator(root, "--check");
    assert.equal(edited.code, 1);
    assert.match(edited.output, /pnpm db:types/);
    // 검사는 고치지 않는다. 생성물은 손댄 그대로 남는다.
    assert.notEqual(readFileSync(join(root, WEB_TYPES), "utf8"), fresh);

    writeFileSync(join(root, WEB_TYPES), fresh);
    writeFiles(root, {
      "supabase/migrations/20260102000001_add_tags.sql":
        "alter table public.notes add column tags text[];\n",
    });
    const added = runGenerator(root, "--check");
    assert.equal(added.code, 1);
    assert.match(added.output, /web\/lib\/database\.types\.ts/);
  });

  it("마이그레이션 이름이 규칙에 어긋나면 아무것도 만들지 않고 실패한다", (t) => {
    const root = webOnlyRepo(t);
    writeFiles(root, { "supabase/migrations/add_tags.sql": "select 1;\n" });

    const { code, output } = runGenerator(root);

    assert.equal(code, 1);
    assert.match(output, /add_tags\.sql/);
    assert.equal(existsSync(join(root, WEB_TYPES)), false);
  });

  it("마이그레이션이 PostgreSQL 에서 실패하면 그 파일 이름과 함께 실패한다", (t) => {
    const root = webOnlyRepo(t);
    writeFiles(root, {
      "supabase/migrations/20260102000001_broken.sql":
        "alter table public.nope add column x int;\n",
    });

    const { code, output } = runGenerator(root);

    assert.equal(code, 1);
    assert.match(output, /20260102000001_broken\.sql/);
    assert.equal(existsSync(join(root, WEB_TYPES)), false);
  });

  it("web·mobile 이 모두 없으면 건너뛴다", (t) => {
    const root = tempDir(t);

    const { code, output } = runGenerator(root, "--check");

    assert.equal(code, 0);
    assert.match(output, /건너뜁니다/);
  });
});
